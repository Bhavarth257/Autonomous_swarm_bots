"""Render a Layout as a Gazebo Fortress (SDF 1.8) world."""
from __future__ import annotations

from rescue_world.layout import AMBIENT_K, Layout


def _f(*vals):
    return ' '.join(f'{v:.4f}' for v in vals)


def _geometry(p):
    if p.shape == 'box':
        return f'<box><size>{_f(*p.size)}</size></box>'
    if p.shape == 'sphere':
        return f'<sphere><radius>{p.size[0]:.4f}</radius></sphere>'
    return f'<cylinder><radius>{p.size[0]:.4f}</radius><length>{p.size[1]:.4f}</length></cylinder>'


def _part(p):
    geom = _geometry(p)
    col = _f(*p.color)
    thermal = ''
    if p.temperature is not None:
        thermal = ('<plugin filename="ignition-gazebo-thermal-system" '
                   'name="ignition::gazebo::systems::Thermal">'
                   f'<temperature>{p.temperature:.1f}</temperature></plugin>')
    out = (f'<visual name="{p.name}_v"><pose>{_f(*p.pose)}</pose><geometry>{geom}</geometry>'
           f'<material><ambient>{col} 1</ambient><diffuse>{col} 1</diffuse>'
           f'<specular>0.05 0.05 0.05 1</specular></material>{thermal}</visual>')
    if p.collide:
        out += f'<collision name="{p.name}_c"><pose>{_f(*p.pose)}</pose><geometry>{geom}</geometry></collision>'
    return out


def _model(name, pose, parts):
    body = '\n      '.join(_part(p) for p in parts)
    return (f'  <model name="{name}">\n    <static>true</static>\n    <pose>{_f(*pose)}</pose>\n'
            f'    <link name="link">\n      {body}\n    </link>\n  </model>\n')


def to_sdf(layout: Layout, world_name='collapsed_building') -> str:
    victims = ''.join(_model(v.id, (v.x, v.y, 0, 0, 0, v.yaw), v.parts) for v in layout.victims)
    W, H = layout.width, layout.height
    return f'''<?xml version="1.0"?>
<!-- Generated by rescue_world (seed {layout.seed}, attempt {layout.attempt}). Do not edit. -->
<sdf version="1.8">
<world name="{world_name}">
  <physics name="4ms" type="ignored">
    <max_step_size>0.004</max_step_size>
    <real_time_factor>1.0</real_time_factor>
  </physics>
  <plugin filename="ignition-gazebo-physics-system" name="ignition::gazebo::systems::Physics"/>
  <plugin filename="ignition-gazebo-user-commands-system" name="ignition::gazebo::systems::UserCommands"/>
  <plugin filename="ignition-gazebo-scene-broadcaster-system" name="ignition::gazebo::systems::SceneBroadcaster"/>
  <plugin filename="ignition-gazebo-sensors-system" name="ignition::gazebo::systems::Sensors">
    <render_engine>ogre2</render_engine>
  </plugin>
  <plugin filename="ignition-gazebo-imu-system" name="ignition::gazebo::systems::Imu"/>

  <atmosphere type="adiabatic">
    <temperature>{AMBIENT_K:.1f}</temperature>
    <temperature_gradient>0</temperature_gradient>
  </atmosphere>
  <scene>
    <ambient>0.45 0.45 0.45 1</ambient>
    <background>0.62 0.60 0.56 1</background>
    <shadows>true</shadows>
    <grid>false</grid>
  </scene>
  <light type="directional" name="sun">
    <cast_shadows>true</cast_shadows>
    <pose>{_f(W / 2, H / 2, 20, 0, 0, 0)}</pose>
    <diffuse>0.85 0.82 0.78 1</diffuse>
    <specular>0.2 0.2 0.2 1</specular>
    <direction>-0.4 0.3 -0.9</direction>
  </light>

  <model name="ground">
    <static>true</static>
    <link name="link">
      <collision name="c"><geometry><plane><normal>0 0 1</normal><size>200 200</size></plane></geometry></collision>
      <visual name="v"><geometry><plane><normal>0 0 1</normal><size>200 200</size></plane></geometry>
        <material><ambient>0.48 0.46 0.42 1</ambient><diffuse>0.48 0.46 0.42 1</diffuse><specular>0.02 0.02 0.02 1</specular></material>
      </visual>
    </link>
  </model>

{_model('structure', (0, 0, 0, 0, 0, 0), layout.parts)}
{victims}
</world>
</sdf>
'''
